def smin(a, b, k):
    k = max(k, 1e-4); h = np.maximum(k - np.abs(a - b), 0) / k; return np.minimum(a, b) - h*h*k*0.25
def prim_np(pr, p):
    t = pr[0]
    if t == "ell":
        c, r = np.array(pr[1]), np.array(pr[2]); q = p - c; k0 = np.linalg.norm(q/r, axis=1); k1 = np.linalg.norm(q/(r*r), axis=1); return k0*(k0-1)/(k1+1e-9)
    if t == "cap":
        a, b = np.array(pr[1]), np.array(pr[2]); ba = b - a; pa = p - a; h = np.clip((pa@ba)/(ba@ba), 0, 1)
        return np.linalg.norm(pa - h[:, None]*ba, axis=1) - (pr[3] + (pr[4]-pr[3])*h)
    if t == "box":
        c, hh, rr = np.array(pr[1]), np.array(pr[2]), pr[3]; q = np.abs(p - c) - hh
        return np.linalg.norm(np.maximum(q, 0), axis=1) + np.minimum(q.max(1), 0) - rr
    if t == "cut":
        return p @ np.array(pr[1]) - pr[2]
def sdf_np(reg, p):
    d = None
    for op, k, pr in REGIONS[reg]:
        e = prim_np(pr, p)
        if d is None: d = e
        elif op == "U": d = smin(d, e, k)
        elif op == "S": d = -smin(-d, e, k)
        elif op == "I": d = -smin(-d, -e, k)
    return d
def v3(x): return "vec3(%s)" % ",".join("%.4f" % v for v in x)
def glsl(reg):
    L = ["float sdf_%s(vec3 p){ float d, e;" % reg.replace(" ", "")]
    for j, (op, k, pr) in enumerate(REGIONS[reg]):
        t = pr[0]
        if t == "ell": s = "sdEll(p,%s,%s)" % (v3(pr[1]), v3(pr[2]))
        elif t == "cap": s = "sdCap(p,%s,%s,%.4f,%.4f)" % (v3(pr[1]), v3(pr[2]), pr[3], pr[4])
        elif t == "box": s = "sdBox(p,%s,%s,%.4f)" % (v3(pr[1]), v3(pr[2]), pr[3])
        elif t == "cut": s = "(dot(p,%s)-(%.4f))" % (v3(pr[1]), pr[2])
        if j == 0: L.append(" d=%s;" % s)
        elif op == "U": L.append(" e=%s; d=smin(d,e,%.4f);" % (s, max(k, 1e-4)))
        elif op == "S": L.append(" e=%s; d=-smin(-d,e,%.4f);" % (s, max(k, 1e-4)))
        elif op == "I": L.append(" e=%s; d=-smin(-d,-e,%.4f);" % (s, max(k, 1e-4)))
    L.append(" return d;}")
    return "\n".join(L)
