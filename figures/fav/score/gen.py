# Forearm score v2 — patina song generator. bpm 60: one beat = one second of video.
import json, sys
from timeline import load, SIDE, POS
T,EV,DUR,CAP=load()
T2,T3,T4,T5=T['T2'],T['T3'],T['T4'],T['T5']
X=json.load(open('../fa_nn.json'))['left']['x']
xs=sorted(set(X)); RANK=[xs.index(x) for x in X]           # 0 elbow .. 9 wrist
LADDER=['A4','B4','D5','E5','F#5','A5','B5','D6','E6','F#6']  # D major pentatonic, elbow low -> wrist high
NM=['C','C#','D','Eb','E','F','F#','G','Ab','A','Bb','B']
def midi(n):
    import re; m=re.match(r'([A-G][#b]?)(-?\d)',n); p={'C':0,'C#':1,'Db':1,'D':2,'Eb':3,'D#':3,'E':4,'F':5,'F#':6,'Gb':6,'G':7,'Ab':8,'G#':8,'A':9,'Bb':10,'A#':10,'B':11}[m.group(1)]
    return 12*(int(m.group(2))+1)+p
def nn(m): return f"{NM[m%12]}{m//12-1}"
def tr(n,k): return nn(midi(n)+k)
f=lambda x:(f"{x:.4f}".rstrip('0').rstrip('.') or '0')
# side -> (track, octave shift)
STRK={0:('s_in',0),1:('s_th',0),2:('s_bk',0),3:('s_lt',0)}
lanes={k:[] for k in ['s_in','s_th','s_bk','s_lt','glide','chime','feather','lead','pad','air','bass','echoes']}
def put(track,t,note,dur,vel): lanes[track].append((t,note,dur,vel))
def spot_note(i): s=SIDE[i]; trk,o=STRK[s]; return trk,tr(LADDER[RANK[i]],o)

# ---- scene 1: spots
for e in EV:
    if e['kind']!='spot': continue
    trk,n=spot_note(e['i'])
    if e['example']:
        put(trk,e['t'],n,2.0,0.55)
    else:
        put(trk,e['t'],n,0.6,0.50+0.25*RANK[e['i']]/9)
# ---- links
for e in EV:
    if e['kind'] not in('linkA','linkB'): continue
    i,j=e['i'],e['j']; ti,ni=spot_note(i); tj,nj=spot_note(j)
    t0,t1=e['t'],e['end']
    if e['example']:
        put(ti,t0,ni,1.5,0.5); put(tj,t1,nj,2.5,0.5)
        # the travelling tone: A slides along the arm, B stays put
        put('glide',t0,f"{ni}>{nj}" if ni!=nj else ni,(t1-t0)+0.8,0.45)
        put('chime',t0,'D6',3,0.55); put('chime',t0+0.02,'A6',3,0.35)
    else:
        v=0.6
        put(ti,t0,ni,0.5,v); put(tj,t1-0.05,nj,0.6,v*0.9)
put('chime',1.4,'D6',3,0.55); put('chime',1.42,'A6',3,0.32)
put('feather',0.75,'A5',1.5,0.5)

# ---- harmony (time, pad voicing, bass)
H=[(0.0,'A3 D4 E4 F#4','D2'),(7.6,'F#3 B3 D4 A4','B1'),(12.3,'G3 B3 D4 F#4','G1'),
   (T2,'G3 B3 D4 F#4','E2'),(T2+2.7,'A3 D4 E4','A1'),
   (T3,'A3 C#4 E4 F#4','D2'),(28.0,'F#3 A3 C#4 D4','B1'),(31.0,'G3 B3 D4 F#4','G1'),(34.0,'A3 B3 E4','A1'),
   (T4,'F#3 A3 C#4 D4','B1'),(41.0,'G3 B3 D4 F#4','E2'),(45.0,'G3 A3 B3 D4','G1'),(48.6,'G3 A3 D4 E4','A1'),
   (T5,'A3 C#4 E4 F#4 A4','D2'),(56.0,'F#3 A3 C#4 D4 E4','B1'),(T5+7.5,'G3 B3 D4 F#4','G1'),(63.4,'A3 B3 E4','A1'),
   (64.9,'A3 D4 E4 F#4','D2')]
for k,(t,v,b) in enumerate(H):
    e=H[k+1][0] if k+1<len(H) else DUR
    vel=0.5 if t<T5 else 0.6
    put('pad',t,'['+v+']',e-t+0.05,vel)
    top=v.split()[-1:]
    put('air',t,'['+' '.join(tr(n,12) for n in top)+']',e-t+0.05,0.45)
    put('bass',t,b,e-t+0.05,0.6)

# ---- lead (t, dur, note[, bend], vel)
L=[(16.3,0.9,'B4',0.5),(17.2,0.6,'D5',0.55),(17.8,1.4,'E5',0.62),(19.2,0.5,'D5',0.5),(19.7,1.5,'E5',0.55),
   (30.5,0.9,'E5>F#5',0.55),(31.4,0.8,'A5',0.6),(32.2,1.6,'B5',0.68),(33.8,0.5,'A5',0.55),(34.3,0.5,'F#5',0.52),(34.8,2.0,'E5',0.5),
   (46.9,0.7,'D5',0.5),(47.6,0.7,'E5',0.55),(48.3,1.2,'F#5',0.62),(49.5,0.9,'A5',0.66),(50.4,0.6,'G5',0.6),(51.0,1.43,'A5',0.7),
   (T5,0.9,'A5>F#6',0.85),(T5+0.9,2.3,'F#6',0.8),(55.6,0.6,'E6',0.7),(56.2,0.8,'D6',0.66),(57.0,1.2,'B5',0.6),(58.2,1.7,'A5',0.55),
   (60.2,1.2,'F#5',0.5),(61.4,0.8,'E5',0.46),(62.2,1.0,'D5',0.44),(63.2,1.6,'E5',0.42),(64.8,2.6,'E5>D5',0.4)]
for t,d,n,v in L: put('lead',t,n,d,v)

# ---- recap echoes in scene 5: the two maps, slowly (32B intervals, then word unisons)
A=[e for e in EV if e['kind']=='linkA' and not e['example']][::6][:4]
B=[e for e in EV if e['kind']=='linkB' and not e['example']][::7][:4]
for k,e in enumerate(A):
    t=56.2+k*0.9; _,ni=spot_note(e['i']); _,nj=spot_note(e['j']); put('echoes',t,tr(ni,0),0.8,0.22); put('echoes',t+0.4,tr(nj,0),0.9,0.2)
for k,e in enumerate(B):
    t=60.5+k*0.9; ti,ni=spot_note(e['i']); tj,nj=spot_note(e['j']); put(ti,t,ni,0.8,0.2); put(tj,t+0.4,nj,0.9,0.18)

