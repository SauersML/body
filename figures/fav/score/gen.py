TRK={
 'pad':  "track pad patch=vellum vel=0.55 gain=0.6 eq_low=-5 eq_low_freq=180 reverb_send=0.3 chorus_send=0.3",
 'air':  "track air additive add_partials=12 add_tilt=1.9 add_spread=7 add_width=0.9 attack=3 release=4 gain=0.3 reverb_send=0.6",
 'bass': "track bass patch=lowglow gain=1.4",
 'lead': "track lead patch=glasslead gain=2.0 reverb_send=0.35 echo_send=0.18",
 'glide':"track glide patch=skynote gain=0.6 reverb_send=0.5 echo_send=0.3",
 's_in': "track s_in modal=glass modal_decay=1.6 modal_bright=0.9 gain=4 azimuth=-12 distance=1.6 reverb_send=0.35 echo_send=0.22",
 's_th': "track s_th string=pluck str_decay=2.5 str_damp=0.5 str_pos=0.2 str_hard=0.2 gain=1.4 azimuth=-55 distance=1.8 reverb_send=0.3 echo_send=0.2",
 's_bk': "track s_bk modal=bar modal_decay=1.2 modal_hard=0.3 gain=2.0 azimuth=20 distance=2.6 reverb_send=0.35 echo_send=0.2",
 's_lt': "track s_lt patch=tessera-bell gain=2.0 azimuth=55 distance=1.8 reverb_send=0.35 echo_send=0.2",
 'chime':"track chime modal=chime modal_decay=1.2 gain=1.3 reverb_send=0.5 echo_send=0.3",
 'feather':"track feather modal=glass modal_excite=2 attack=0.6 release=0.8 gain=1.3 azimuth=-12 distance=1.2 reverb_send=0.6",
 'echoes':"track echoes modal=glass modal_decay=2 gain=0.9 pan=-0.2 reverb_send=0.6 echo_send=0.35",
}
out=[HEAD]
for k,line in TRK.items():
    out.append(line)
    toks=[]
    for t,n,d,v in sorted(lanes[k]):
        toks.append(f">{f(t)} {n}:{f(d)}@{f(v)}")
    out.append('\n'.join(toks) if toks else 'R:1')
# expressive lanes: vibrato that blooms inside each held note, deeper on long notes
def vib_lanes():
    pts=[(0.0,0.0)]; rate=[(0.0,4.6)]
    for t,d,n,v in L:
        pts.append((t,0.0)); dl=min(0.35,d*0.3); full=min(26,8+10*d)*(0.7+0.5*v)
        pts.append((t+dl,0.0)); pts.append((t+d*0.95,full))
        rate.append((t,4.4)); rate.append((t+d*0.95,4.6+0.6*min(1,d/2)))
    def lane(p,shape):
        o=[f(p[0][1])]; cur=0.0
        for (t,val) in p[1:]:
            if t<=cur+1e-4: o.append(f"{f(val)}:0.0001@step"); cur+=0.0001; continue
            o.append(f"{f(val)}:{f(t-cur)}@{shape}"); cur=t
        return ' '.join(o)
    return f"automate lead.glide\n0\nautomate lead.lfo_pitch\n{lane(pts,'smooth')}\nautomate lead.lfo_rate\n{lane(rate,'smooth')}\n"
VIB=vib_lanes()
import numpy as np
def padg():
    arc=[(0,0.45),(15,0.6),(30,0.72),(45,0.78),(52.0,0.9),(53.0,1.0),(57,0.9),(64,0.42),(68.5,0.4)]
    ts=np.arange(0,68.5,0.25); base=np.interp(ts,[a for a,_ in arc],[b for _,b in arc])
    act=np.zeros_like(ts)
    for t,d,n,v in L: act[(ts>=t-0.3)&(ts<=t+d+0.2)]=1
    k=np.ones(5)/5; act=np.convolve(act,k,'same')
    dense=np.zeros_like(ts)
    for a,b in [(5.0,15.2),(24.9,30.8),(40.9,47.0)]: dense[(ts>=a)&(ts<=b)]=1
    dense=np.convolve(dense,np.ones(7)/7,'same')
    g=base*(1-0.28*act)*(1-0.25*dense)
    return 'automate pad.gain\n'+f(g[0])+' '+' '.join(f"{f(x)}:0.25" for x in g[1:])+'\n'
PADG=padg()
out.append(""""""+VIB+"""automate lead.cutoff
2200 R:30 3200:22@exp 4200:2@smooth 2600:14@exp
automate pad.cutoff
900 {1100+500*noise(b/5)+900*smoothstep(20,36,b)-300*smoothstep(36,50,b)+1300*smoothstep(51,53,b)*(1-smoothstep(56,67,b))}:68
automate output
1 R:65.6 0.0:2.4@smooth
automate air.add_comb_phase
0 {b*0.35}:68
automate air.add_comb_depth
0.5
"""+PADG+"""""")
open('forearm.song','w').write('\n'.join(out)+'\n')
