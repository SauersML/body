# Body-map score (patina). bpm 60: one beat = one second of video. Driven by timing.json.
import json, random
random.seed(3)
J=json.load(open('timing.json')); SC={s['name']:s for s in J['scenes']}; DUR=J['video_length_s']
T1,T2=SC['touch']['touches']
MO,OR,OV,OP,RB,EB=[SC[k] for k in ['morph_out','orbit','mirror_overlap','mirror_open','return_to_body','end_on_body']]
f=lambda x:(f"{x:.3f}".rstrip('0').rstrip('.') or '0')
lanes={}
def put(tr,t,n,d,v): lanes.setdefault(tr,[]).append((t,n,d,v))
# ---- harmony: (time, voicing, bass)
H=[(0.0,'D3 A3 E4 F#4','D2'),(4.0,'B2 F#3 A3 D4','B1'),(7.2,'G2 D3 A3 B3','G1'),(9.3,'E3 G3 B3 D4','E2'),(11.1,'G2 D3 F#3 B3','G1'),(12.8,'A2 E3 G3 B3','A1'),
   (MO['start'],'D3 A3 E4 F#4','D2'),(17.0,'B2 F#3 A3 D4 E4','B1'),(MO['label_in'],'G2 D3 A3 B3 F#4','G1'),(OR['start'],'D3 F#3 A3 E4','F#1'),
   (24.5,'G2 B2 F#3 A3 D4','G1'),(27.5,'E3 G3 B3 D4 F#4','E2'),(30.3,'A2 E3 G3 B3 D4','A1'),
   (OV['start'],'D3 A3 D4 E4','D2'),(OP['start'],'B2 F#3 D4 E4 A4','B1'),(39.0,'G2 D3 B3 F#4 A4','G1'),
   (RB['start'],'E3 G3 B3 D4','E2'),(44.2,'G2 D3 A3 B3','G1'),(46.3,'A2 E3 G3 C#4 E4','A1'),
   (EB['start'],'D3 A3 E4 F#4 A4','D2')]
for k,(t,v,b) in enumerate(H):
    e=H[k+1][0] if k+1<len(H) else DUR
    put('pad',t,'['+v+']',e-t+0.08,0.5)
    put('bass',t,b,e-t+0.05,0.55)
    top=v.split()[-1]; up=top[:-1]+str(int(top[-1])+1)
    put('air',t,f'[{up}]',e-t+0.08,0.4)
# ---- the two touches: a tone falls with the dot, a glass bell rings where the dot lands
put('glide',T1['drop'],'A6>D6',T1['land']-T1['drop']+0.6,0.42); put('bell',T1['land'],'D6',3.0,0.6); put('bell',T1['land']+0.02,'A6',3.0,0.32)
put('glide',T2['drop'],'B6>E6',T2['land']-T2['drop']+0.6,0.42); put('bell',T2['land'],'E6',3.0,0.6); put('bell',T2['land']+0.02,'B6',3.0,0.32)
put('bell',0.7,'A5',3,0.38); put('bell',1.9,'F#5',3,0.3)
# ---- sparkle: rising arpeggio while the points fly out, slower glints during the turn
CH={14:'D5 E5 F#5 A5 B5 D6',17:'B4 D5 F#5 A5 B5 E6',18.5:'D5 G5 A5 B5 D6 F#6',21.8:'D5 F#5 A5 C#6 E6',24.5:'D5 F#5 G5 A5 B5 D6',27.5:'E5 G5 B5 D6 F#6',30.3:'E5 G5 A5 B5 D6'}
def chord_at(t): return CH[max(k for k in CH if k<=t)].split()
t=MO['start']; k=0
while t<OR['end']:
    c=chord_at(t); n=c[k%len(c)] if t<MO['end'] else random.choice(c)
    v=0.22+0.16*min(1,(t-MO['start'])/5)*(1 if t<26 else max(0.3,1-(t-26)/7))
    put('arp',t,n,0.9,v); k+=1
    t+= 0.25 if t<MO['end'] else 0.5
# ---- lead (time, dur, note, vel)
L=[(15.6,0.8,'A4',0.42),(16.4,0.6,'D5',0.5),(17.0,1.5,'E5',0.56),(18.5,0.7,'F#5',0.6),(19.2,2.4,'A5',0.66),
   (22.2,0.9,'B5>A5',0.6),(23.1,0.6,'F#5',0.55),(23.7,2.4,'E5',0.55),(26.3,0.6,'D5',0.5),(26.9,0.6,'E5',0.55),(27.5,1.0,'F#5',0.6),(28.5,0.8,'B5',0.64),(29.3,1.0,'A5',0.6),(30.3,2.4,'E5',0.52)]
for t,d,n,v in L: put('lead',t,n,d,v)
# ---- mirror: two voices in unison (left and right on top of each other), then opening into mirrored lines
o0,o1=OV['start']+0.2,OP['start']
for tr in ('mL','mR'): put(tr,o0,'A5',o1-o0+0.02,0.5)
UPL=[(o1,1.4,'A5>D6'),(o1+1.4,1.2,'D6>E6'),(o1+2.6,2.2,'E6>F#6')]
DNR=[(o1,1.4,'A5>F#5'),(o1+1.4,1.2,'F#5>E5'),(o1+2.6,2.2,'E5>D5')]
for t,d,n in UPL: put('mL',t,n,d,0.5)
for t,d,n in DNR: put('mR',t,n,d,0.5)
# ---- return to the body: the line comes home
R=[(RB['start']+0.3,1.2,'F#5',0.5),(RB['start']+1.5,0.8,'E5',0.46),(RB['start']+2.3,1.6,'D5',0.46),(44.4,1.2,'B4',0.42),(45.6,0.7,'D5',0.42),(46.3,1.9,'C#5',0.42),(EB['start'],2.6,'D5',0.38)]
for t,d,n,v in R: put('lead',t,n,d,v)
put('bell',EB['start'],'A5',3.5,0.4); put('bell',EB['start']+0.04,'F#6',3.5,0.22)
HEAD=f"""# Body map score (generated by gen.py from timing.json; bpm 60 = seconds)
bpm 60
gate 0.97
tail 0.5
automate reverb_wet
0.34
automate reverb_decay
0.88
automate echo_time
0.5
automate echo_feedback
0.32
automate echo_tone
3200
automate chorus_mode
2
automate chorus_depth
0.25
automate tape_wow
0.1
automate tape_age
0.25
"""
TRK={
 'pad':  "track pad patch=dreampad vel=0.5 gain=0.62 eq_low=-4 eq_low_freq=170 reverb_send=0.3",
 'air':  "track air additive add_partials=12 add_tilt=1.9 add_spread=7 add_width=0.9 attack=3 release=4 gain=0.26 reverb_send=0.6",
 'bass': "track bass patch=deepsine gain=1.3",
 'lead': "track lead patch=glasslead gain=1.8 reverb_send=0.38 echo_send=0.2",
 'mL':   "track mL patch=glasslead gain=1.5 azimuth=-55 reverb_send=0.4 echo_send=0.18",
 'mR':   "track mR patch=glasslead gain=1.5 azimuth=55 reverb_send=0.4 echo_send=0.18",
 'glide':"track glide patch=skynote gain=0.6 reverb_send=0.5 echo_send=0.3",
 'bell': "track bell modal=glass modal_decay=1.8 modal_bright=0.9 gain=2.4 reverb_send=0.45 echo_send=0.25",
 'arp':  "track arp patch=glintbell gain=0.9 reverb_send=0.5 echo_send=0.3",
}
out=[HEAD]
for k,line in TRK.items():
    out.append(line); out.append('\n'.join(f">{f(t)} {n}:{f(d)}@{f(v)}" for t,n,d,v in sorted(lanes.get(k,[]))) or 'R:1')
out.append(f"""automate pad.cutoff
700 1500:8@exp 2600:8@exp 2900:10@smooth 2200:8@smooth 3000:6@smooth 1200:7@exp 700:4@exp
automate lead.cutoff
2400 R:18 3600:12@exp 3000:10@smooth 2200:11@exp
automate output
0.0 1:0.8@smooth R:{f(DUR-3.6)} 0.0:2.8@smooth
""")
open('body.song','w').write('\n'.join(out)+'\n'); print('ok',{k:len(v) for k,v in lanes.items()})
